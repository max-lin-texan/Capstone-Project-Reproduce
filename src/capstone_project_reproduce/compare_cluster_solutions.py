"""Compare existing NNCPD patient-clustering solutions without refitting.

This script compares the standard k=2 output with the exploratory k=4 output
already generated by ``patient_clustering.py``.
"""

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.metrics import adjusted_mutual_info_score, adjusted_rand_score

PROJECT_DIR = Path(__file__).resolve().parents[2]
RESULTS_ROOT = PROJECT_DIR / "results"
MODEL_NAME = "nncpd_last_rank9"
STANDARD_K = 2
CANDIDATE_K = 4
CLUSTER_METHODS = ("kmeans", "hierarchical")


def load_solution_metrics(model_root: Path) -> pd.DataFrame:
    """Combine the existing k=2 metrics and candidate k=4 metrics."""
    standard = pd.read_csv(model_root / "clustering_metrics.csv")
    candidate = pd.read_csv(
        model_root / f"candidate_k{CANDIDATE_K}" / "candidate_metrics.csv"
    )
    standard = standard[standard["cluster_count"].eq(STANDARD_K)].copy()
    candidate = candidate[candidate["cluster_count"].eq(CANDIDATE_K)].copy()
    standard["solution"] = f"k{STANDARD_K}"
    candidate["solution"] = f"k{CANDIDATE_K}"
    return pd.concat([standard, candidate], ignore_index=True)


def load_cluster_sizes(model_root: Path) -> pd.DataFrame:
    """Calculate cluster counts and percentages for both existing solutions."""
    frames = []
    for cluster_count, directory, filename in (
        (STANDARD_K, model_root, "cluster_labels.csv"),
        (
            CANDIDATE_K,
            model_root / f"candidate_k{CANDIDATE_K}",
            "candidate_cluster_labels.csv",
        ),
    ):
        labels = pd.read_csv(directory / filename)
        labels = labels[labels["cluster_count"].eq(cluster_count)].copy()
        counts = (
            labels.groupby(["clustering_method", "cluster_label"])
            .size()
            .rename("patient_count")
            .reset_index()
        )
        counts["cluster_count"] = cluster_count
        counts["solution"] = f"k{cluster_count}"
        counts["patient_fraction"] = counts["patient_count"] / labels["patientunitstayid"].nunique()
        frames.append(counts)
    return pd.concat(frames, ignore_index=True)


def load_profiles(model_root: Path) -> pd.DataFrame:
    """Load component profiles for k=2 and k=4."""
    standard = pd.read_csv(model_root / "cluster_profiles.csv")
    candidate = pd.read_csv(
        model_root / f"candidate_k{CANDIDATE_K}" / "candidate_cluster_profiles.csv"
    )
    standard = standard[standard["cluster_count"].eq(STANDARD_K)].copy()
    candidate = candidate[candidate["cluster_count"].eq(CANDIDATE_K)].copy()
    standard["solution"] = f"k{STANDARD_K}"
    candidate["solution"] = f"k{CANDIDATE_K}"
    return pd.concat([standard, candidate], ignore_index=True)


def load_labels(model_root: Path, method: str, cluster_count: int) -> pd.DataFrame:
    """Load labels for one method and one k from existing outputs."""
    if cluster_count == STANDARD_K:
        path = model_root / "cluster_labels.csv"
    else:
        path = model_root / f"candidate_k{cluster_count}" / "candidate_cluster_labels.csv"
    labels = pd.read_csv(path)
    return labels[
        labels["clustering_method"].eq(method)
        & labels["cluster_count"].eq(cluster_count)
    ][["patientunitstayid", "cluster_label"]].rename(
        columns={"cluster_label": f"cluster_k{cluster_count}"}
    )


def cosine_similarity_matrix(left: pd.DataFrame, right: pd.DataFrame) -> pd.DataFrame:
    """Calculate profile cosine similarities for all k=2/k=4 pairs."""
    left_values = left.to_numpy(float, copy=True)
    right_values = right.to_numpy(float, copy=True)
    left_values /= np.linalg.norm(left_values, axis=1, keepdims=True)
    right_values /= np.linalg.norm(right_values, axis=1, keepdims=True)
    return pd.DataFrame(left_values @ right_values.T, index=left.index, columns=right.index)


def build_alignment_outputs(
    model_root: Path,
    profiles: pd.DataFrame,
    output: Path,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Compare k=2/k=4 profiles and patient assignments for each method."""
    profile_rows: list[dict[str, object]] = []
    overlap_rows: list[dict[str, object]] = []
    summary_rows: list[dict[str, object]] = []
    for method in CLUSTER_METHODS:
        method_profiles = profiles[profiles["clustering_method"].eq(method)]
        component_columns = sorted(method_profiles["component"].unique())
        matrices = {}
        for solution, cluster_count in (("k2", STANDARD_K), ("k4", CANDIDATE_K)):
            pivot = method_profiles[method_profiles["solution"].eq(solution)].pivot(
                index="cluster",
                columns="component",
                values="mean_standardized_score",
            )
            matrices[solution] = pivot.reindex(columns=component_columns)
        similarity = cosine_similarity_matrix(matrices["k2"], matrices["k4"])
        for k2_cluster in similarity.index:
            for k4_cluster in similarity.columns:
                profile_rows.append(
                    {
                        "clustering_method": method,
                        "k2_cluster": int(k2_cluster),
                        "k4_cluster": int(k4_cluster),
                        "profile_cosine_similarity": float(similarity.loc[k2_cluster, k4_cluster]),
                    }
                )

        k2_labels = load_labels(model_root, method, STANDARD_K)
        k4_labels = load_labels(model_root, method, CANDIDATE_K)
        merged = k2_labels.merge(k4_labels, on="patientunitstayid", how="inner")
        overlap = pd.crosstab(merged["cluster_k2"], merged["cluster_k4"])
        for k2_cluster in overlap.index:
            total = overlap.loc[k2_cluster].sum()
            for k4_cluster in overlap.columns:
                overlap_rows.append(
                    {
                        "clustering_method": method,
                        "k2_cluster": int(k2_cluster),
                        "k4_cluster": int(k4_cluster),
                        "patient_count": int(overlap.loc[k2_cluster, k4_cluster]),
                        "fraction_within_k2_cluster": float(
                            overlap.loc[k2_cluster, k4_cluster] / total
                        ),
                    }
                )
        summary_rows.append(
            {
                "clustering_method": method,
                "adjusted_rand_index": float(
                    adjusted_rand_score(merged["cluster_k2"], merged["cluster_k4"])
                ),
                "adjusted_mutual_info": float(
                    adjusted_mutual_info_score(merged["cluster_k2"], merged["cluster_k4"])
                ),
            }
        )

    profile_frame = pd.DataFrame(profile_rows)
    overlap_frame = pd.DataFrame(overlap_rows)
    pd.DataFrame(summary_rows).to_csv(output / "alignment_summary.csv", index=False, float_format="%.6f")
    profile_frame.to_csv(output / "profile_alignment.csv", index=False, float_format="%.6f")
    overlap_frame.to_csv(output / "cluster_assignment_overlap.csv", index=False, float_format="%.6f")
    return profile_frame, overlap_frame


def plot_alignment(profile_frame: pd.DataFrame, overlap_frame: pd.DataFrame, path: Path) -> None:
    """Plot profile similarity and k=2-to-k=4 patient assignment overlap."""
    figure, axes = plt.subplots(2, 2, figsize=(12, 9), constrained_layout=True)
    for column, method in enumerate(CLUSTER_METHODS):
        profile = profile_frame[profile_frame["clustering_method"].eq(method)]
        profile_matrix = profile.pivot(
            index="k2_cluster", columns="k4_cluster", values="profile_cosine_similarity"
        )
        image = axes[0, column].imshow(profile_matrix.to_numpy(float), vmin=-1, vmax=1, cmap="coolwarm")
        axes[0, column].set_title(f"{method.upper()} profile cosine")
        axes[0, column].set_xlabel("k=4 cluster")
        axes[0, column].set_ylabel("k=2 cluster")
        axes[0, column].set_xticks(range(len(profile_matrix.columns)))
        axes[0, column].set_yticks(range(len(profile_matrix.index)))
        axes[0, column].set_xticklabels([f"C{int(value) + 1}" for value in profile_matrix.columns])
        axes[0, column].set_yticklabels([f"C{int(value) + 1}" for value in profile_matrix.index])
        for row in range(profile_matrix.shape[0]):
            for col in range(profile_matrix.shape[1]):
                axes[0, column].text(col, row, f"{profile_matrix.iloc[row, col]:.2f}", ha="center", va="center")

        overlap = overlap_frame[overlap_frame["clustering_method"].eq(method)]
        overlap_matrix = overlap.pivot(
            index="k2_cluster", columns="k4_cluster", values="fraction_within_k2_cluster"
        )
        axes[1, column].imshow(overlap_matrix.to_numpy(float), vmin=0, vmax=1, cmap="Blues")
        axes[1, column].set_title(f"{method.upper()} assignment overlap")
        axes[1, column].set_xlabel("k=4 cluster")
        axes[1, column].set_ylabel("k=2 cluster")
        axes[1, column].set_xticks(range(len(overlap_matrix.columns)))
        axes[1, column].set_yticks(range(len(overlap_matrix.index)))
        axes[1, column].set_xticklabels([f"C{int(value) + 1}" for value in overlap_matrix.columns])
        axes[1, column].set_yticklabels([f"C{int(value) + 1}" for value in overlap_matrix.index])
        for row in range(overlap_matrix.shape[0]):
            for col in range(overlap_matrix.shape[1]):
                axes[1, column].text(col, row, f"{overlap_matrix.iloc[row, col]:.2f}", ha="center", va="center")
    figure.suptitle("NNCPD k=2 to k=4 alignment")
    figure.savefig(path, dpi=150)
    plt.close(figure)


def plot_metrics(metrics: pd.DataFrame, path: Path) -> None:
    """Plot the three metrics for k=2 versus k=4."""
    definitions = [
        ("silhouette_score", "Silhouette score", True),
        ("calinski_harabasz_score", "Calinski-Harabasz score", True),
        ("davies_bouldin_score", "Davies-Bouldin score", False),
    ]
    figure, axes = plt.subplots(1, 3, figsize=(15, 5), constrained_layout=True)
    x = np.arange(len(CLUSTER_METHODS))
    width = 0.35
    colors = {"k2": "#08519C", "k4": "#CB181D"}
    for axis, (column, title, higher_is_better) in zip(axes, definitions):
        for offset, solution in zip((-width / 2, width / 2), ("k2", "k4")):
            values = [
                metrics.loc[
                    metrics["clustering_method"].eq(method)
                    & metrics["solution"].eq(solution),
                    column,
                ].iloc[0]
                for method in CLUSTER_METHODS
            ]
            bars = axis.bar(x + offset, values, width, label=solution, color=colors[solution])
            for bar, value in zip(bars, values):
                axis.text(
                    bar.get_x() + bar.get_width() / 2,
                    bar.get_height(),
                    f"{value:.3f}" if column == "silhouette_score" else f"{value:.1f}",
                    ha="center",
                    va="bottom",
                    fontsize=8,
                )
        axis.set_title(title)
        axis.set_xticks(x)
        axis.set_xticklabels([method.upper() for method in CLUSTER_METHODS])
        axis.set_ylabel("higher is better" if higher_is_better else "lower is better")
        axis.grid(axis="y", alpha=0.25)
        axis.legend()
    figure.suptitle("NNCPD patient clustering: k=2 versus k=4")
    figure.savefig(path, dpi=150)
    plt.close(figure)


def plot_sizes(sizes: pd.DataFrame, path: Path) -> None:
    """Plot cluster proportions for both methods and both k values."""
    figure, axes = plt.subplots(1, 2, figsize=(12, 5), constrained_layout=True)
    colors = {"k2": "#08519C", "k4": "#CB181D"}
    for axis, method in zip(axes, CLUSTER_METHODS):
        subset = sizes[sizes["clustering_method"].eq(method)]
        labels = [f"{solution} C{int(cluster) + 1}" for solution, cluster in zip(subset["solution"], subset["cluster_label"])]
        bars = axis.bar(labels, subset["patient_fraction"] * 100, color=[colors[value] for value in subset["solution"]])
        axis.set_title(method.upper())
        axis.set_ylabel("Patients (%)")
        axis.tick_params(axis="x", rotation=45)
        for bar, value in zip(bars, subset["patient_fraction"] * 100):
            axis.text(bar.get_x() + bar.get_width() / 2, value, f"{value:.1f}%", ha="center", va="bottom", fontsize=8)
    figure.suptitle("Cluster size comparison")
    figure.savefig(path, dpi=150)
    plt.close(figure)


def plot_profiles(profiles: pd.DataFrame, path: Path) -> None:
    """Plot k=2 and k=4 standardized component profiles."""
    methods = list(CLUSTER_METHODS)
    solutions = ("k2", "k4")
    maximum = float(profiles["mean_standardized_score"].abs().max())
    maximum = max(2.0, min(maximum, 12.0))
    figure, axes = plt.subplots(2, 2, figsize=(14, 9), squeeze=False, constrained_layout=True)
    image = None
    for row, method in enumerate(methods):
        for column, solution in enumerate(solutions):
            subset = profiles[
                profiles["clustering_method"].eq(method)
                & profiles["solution"].eq(solution)
            ]
            pivot = subset.pivot(
                index="cluster",
                columns="component",
                values="mean_standardized_score",
            )
            image = axes[row, column].imshow(
                pivot.to_numpy(float),
                aspect="auto",
                cmap="coolwarm",
                vmin=-maximum,
                vmax=maximum,
            )
            axes[row, column].set_title(f"{method.upper()} {solution}")
            axes[row, column].set_xticks(range(len(pivot.columns)))
            axes[row, column].set_xticklabels(pivot.columns, rotation=90)
            axes[row, column].set_yticks(range(len(pivot.index)))
            axes[row, column].set_yticklabels([f"C{int(value) + 1}" for value in pivot.index])
    figure.suptitle("NNCPD component profiles: k=2 versus k=4")
    figure.colorbar(image, ax=axes.ravel().tolist(), label="Mean standardized factor score")
    figure.savefig(path, dpi=150)
    plt.close(figure)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-root", type=Path, default=RESULTS_ROOT)
    args = parser.parse_args()
    model_root = args.results_root / "patient_clustering" / MODEL_NAME
    output = model_root / "solution_comparison"
    output.mkdir(parents=True, exist_ok=True)

    metrics = load_solution_metrics(model_root)
    sizes = load_cluster_sizes(model_root)
    profiles = load_profiles(model_root)
    metrics.to_csv(output / "solution_comparison.csv", index=False, float_format="%.6f")
    sizes.to_csv(output / "cluster_sizes_comparison.csv", index=False, float_format="%.6f")
    profiles.to_csv(output / "component_profiles_comparison.csv", index=False, float_format="%.6f")
    plot_metrics(metrics, output / "metrics_comparison.png")
    plot_sizes(sizes, output / "cluster_sizes_comparison.png")
    plot_profiles(profiles, output / "component_profiles_comparison.png")
    profile_alignment, assignment_overlap = build_alignment_outputs(model_root, profiles, output)
    plot_alignment(profile_alignment, assignment_overlap, output / "alignment_comparison.png")
    print(f"Saved comparison outputs to {output}")


if __name__ == "__main__":
    main()
